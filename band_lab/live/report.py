@dataclass
class FillWithoutQuote:
    """§5 question 1: did a fill occur without the quote reaching the limit?"""
    bar: Optional[int]
    price: float
    limit_px: float
    best_bid_seen: Optional[float]
    n_quotes: int

    @property
    def suspicious(self) -> bool:
        # Only a positive observation counts. With no quotes recorded there is
        # no evidence either way, and the report must not manufacture some —
        # defects 6 and 7 were both checks that fired on absence of evidence.
        return (self.n_quotes > 0 and self.best_bid_seen is not None
                and self.best_bid_seen > self.limit_px)


def fills_without_quotes(store: Store, symbol: str,
                         session: str) -> list[FillWithoutQuote]:
    quotes = store.rows(
        "SELECT * FROM quotes WHERE session=? AND symbol=? ORDER BY ts",
        (session, symbol))
    limits = entry_limits(store, symbol, session)
    out = []
    for f in store.session_fills(symbol, session):
        if (f["role"] or "") != "E":
            continue
        idx = bar_idx_of(f["ts"])
        cands = [b for b in limits if idx is None or b <= idx]
        if not cands:
            continue
        lim = limits[max(cands)]
        seen = [float(q["bid"]) for q in quotes
                if q["bid"] is not None and (bar_idx_of(q["ts"]) or -1) <= (idx or 10**6)]
        out.append(FillWithoutQuote(bar=idx, price=float(f["price"] or 0.0),
                                    limit_px=lim,
                                    best_bid_seen=min(seen) if seen else None,
                                    n_quotes=len(seen)))
    return out


@dataclass
class SameBarReentry:
    """§5 question 2, and the sharpest available test of S10.

    S10's claim is that the 5-minute backtest books a re-entry at a price that
    had already traded *before* the exit it follows. Live, the re-entry order
    is sent after the exit fills, so it can only trade against prints that come
    after it.

    **What this can and cannot prove.** A live re-entry priced below the exit
    it followed is *not* impossible — the market may simply have fallen after
    the exit, which is an ordinary and profitable event. So `live_better` is
    not a defect detector on its own. What isolates S10 is the comparison:
    `shadow_advantage_bp` on events both sources saw, and the count of
    re-entries the shadow books that the live session never had at all.
    """
    bar: int
    prev_exit_px: float
    live_entry_px: Optional[float]
    shadow_entry_px: Optional[float]

    @property
    def live_better(self) -> Optional[bool]:
        """Did the live re-entry get in below the price it had just sold at?

        §5 question 2 asks for this directly. "At or worse" — i.e. False — is
        the answer S10 predicts should dominate.
        """
        if self.live_entry_px is None:
            return None
        return self.live_entry_px < self.prev_exit_px

    @property
    def shadow_better(self) -> Optional[bool]:
        if self.shadow_entry_px is None:
            return None
        return self.shadow_entry_px < self.prev_exit_px

    @property
    def shadow_advantage_bp(self) -> Optional[float]:
        """How much cheaper the backtest got in, on an event both sources saw.

        Positive means the shadow bought below the live fill — the S10
        exposure, measured in the only place it can be measured directly.
        """
        if self.live_entry_px is None or not self.shadow_entry_px:
            return None
        return (self.live_entry_px / self.shadow_entry_px - 1.0) * 1e4


def same_bar_reentries(live: Sequence[LiveTrade],
                       shadow: Sequence[Trade]) -> list[SameBarReentry]:
    """Re-entries that began in the bar the previous trade exited in."""
    out: list[SameBarReentry] = []

    def _pairs_live():
        for a, b in zip(live, live[1:]):
            if a.exit_bar is not None and b.entry_bar == a.exit_bar:
                yield a.exit_bar, a.exit_px, b.entry_px
    def _pairs_shadow():
        for a, b in zip(shadow, shadow[1:]):
            if b.entry_bar == a.exit_bar:
                yield a.exit_bar, a.exit_px, b.entry_px

    shadow_by_bar = {bar: (xpx, epx) for bar, xpx, epx in _pairs_shadow()}
    for bar, xpx, epx in _pairs_live():
        s = shadow_by_bar.pop(bar, None)
        out.append(SameBarReentry(bar=bar, prev_exit_px=xpx, live_entry_px=epx,
                                  shadow_entry_px=s[1] if s else None))
    # Shadow re-entries the live session never had — the S10 population that
    # simply does not exist in reality. These are the most important rows.
    for bar, (xpx, epx) in sorted(shadow_by_bar.items()):
        out.append(SameBarReentry(bar=bar, prev_exit_px=xpx,
                                  live_entry_px=None, shadow_entry_px=epx))
    return sorted(out, key=lambda r: r.bar)


# ------------------------------------------------------------ §8 monitoring
#: V20's corrected baselines, read in preference to the `spec` file below.
#: Kept separate rather than overwriting `monitoring_expectations.csv` because
#: `parity.py` regenerates that file under `spec` on every run — a corrected
#: value written there is reverted by the next Phase 1 run, silently, in the one
#: number the daily report measures live against.
V20_BASELINES = ("v2_dev", "out", "v20_corrected_baselines.csv")
SPEC_BASELINES = ("phase1", "out", "monitoring_expectations.csv")


def load_baselines(root: str = _BAND_LAB) -> dict[tuple[str, str], float]:
    """§8's baselines: V20's corrected values layered over the `spec` file.

    V20 established that `spec` prices a same-bar re-entry at a price that
    traded *before* the exit it followed, and that live never gets that fill:
    ten such trades appear in the backtest and none in thirteen live
    sleeve-sessions. Comparing live against a baseline built on unavailable
    fills measures the simulator, not the strategy.

    The two files are layered rather than swapped because V20 corrects the
    metrics a fill model can move and no others — `ON_day_rate_%` comes off the
    gate, which is computed from prior sessions, so it still comes from `spec`.
    """
    out: dict[tuple[str, str], float] = {}
    for parts in (SPEC_BASELINES, V20_BASELINES):       # later wins
        path = os.path.join(root, *parts)
        if not os.path.exists(path):
            continue
        with open(path, newline="", encoding="utf-8") as fh:
            for r in csv.DictReader(fh):
                try:
                    out[(r["sleeve"], r["metric"])] = float(r["measured"])
                except (KeyError, TypeError, ValueError):
                    continue
    return out


def baseline_source(root: str = _BAND_LAB) -> str:
    """Which baselines a report is using. Printed, never inferred."""
    return ("V20-corrected (no_better fill model)"
            if os.path.exists(os.path.join(root, *V20_BASELINES))
            else "spec (UNCORRECTED — V20 has not been run)")


@dataclass
class Weekly:
    symbol: str
    sessions: int = 0
    on_days: int = 0
    fills: int = 0
    outcomes: dict = field(default_factory=dict)
    day_returns: list[float] = field(default_factory=list)

    @property
    def on_rate(self) -> Optional[float]:
        return 100.0 * self.on_days / self.sessions if self.sessions else None

    @property
    def fills_per_on_day(self) -> Optional[float]:
        return self.fills / self.on_days if self.on_days else None

    @property
    def gross_bp(self) -> Optional[float]:
        if not self.day_returns:
            return None
        return 1e4 * sum(self.day_returns) / len(self.day_returns)

    @property
    def worst_day(self) -> Optional[float]:
        return 100.0 * min(self.day_returns) if self.day_returns else None

    def outcome_pct(self, name: str) -> Optional[float]:
        total = sum(self.outcomes.values())
        return 100.0 * self.outcomes.get(name, 0) / total if total else None


def weekly(store: Store, symbols: Optional[Sequence[str]] = None,
           sessions: Optional[Sequence[str]] = None) -> dict[str, Weekly]:
    sessions = list(sessions or sessions_in(store))
    acc: dict[str, Weekly] = {}
    for s in sessions:
        for sym in (symbols or symbols_in(store, s)):
            row = daily_row(store, sym, s)
            if row is None:
                continue
            w = acc.setdefault(sym, Weekly(sym))
            w.sessions += 1
            traded = bool(row["gate_ok"]) and bool(row["filter_ok"])
            if not traded:
                continue
            w.on_days += 1
            trades = live_trades(store, sym, s)
            w.fills += len(trades)
            # §8's baselines are the backtest's `sm.pnl`, so the live series
            # compared against them has to be the same quantity — see the note
            # in `print_session_report`. Summing price returns here made
            # `gross_bp_per_ON_day` and `worst_day_%` drift from the engine's
            # own numbers by the gap-through depth of each entry.
            bp, _ = day_bp(trades, _num(row, "sleeve_capital"))
            w.day_returns.append(bp / 1e4)
            for t in trades:
                w.outcomes[t.outcome] = w.outcomes.get(t.outcome, 0) + 1
    return acc


# ------------------------------------------------------------------ printing
def _rule(title: str = "", ch: str = "=", width: int = 78) -> str:
    return ch * width if not title else f"{title} ".ljust(width, ch)


def print_session_report(store: Store, session: str,
                         symbols: Optional[Sequence[str]] = None) -> int:
    """The daily report. Returns the number of findings that need a human."""
    findings = 0
    compared: list[str] = []                    # traded, shadow ran, bars complete
    unverified: list[tuple[str, str]] = []      # traded, shadow did not run
    truncated: list[tuple[str, Coverage]] = []  # traded, shadow ran, bars short
    syms = list(symbols or symbols_in(store, session))
    print(_rule())
    print(f"SESSION {session_label(session)} — shadow parity and fill quality")
    print(_rule())
    if not syms:
        print("\nNo sleeves recorded for this session.")
        return 0

    for sym in syms:
        row = daily_row(store, sym, session)
        bars = recorded_bars(store, sym, session)
        live = live_trades(store, sym, session)
        sh = shadow_replay(bars, row)

        print(f"\n{_rule(sym, '-')}")
        if row is not None:
            print(f"  gate    {'ON ' if row['gate_ok'] else 'OFF'}  "
                  f"{row['gate_reason'] or '':<32} atr5={_fmt(row['atr5'])}")
            print(f"  filter  {'ON ' if row['filter_ok'] else 'OFF'}  "
                  f"{row['filter_reason'] or '':<32} "
                  f"or30={_fmt(row['or30'])} thr80={_fmt(row['thr80'])} "
                  f"pos10={_fmt(row['pos10'], 3)}")
            print(f"  capital {_fmt(row['sleeve_capital'], 0)}   bars recorded: {len(bars)}")

        # --- 1. feature parity
        checks = feature_parity(bars, row)
        for c in checks:
            if not c.ok:
                findings += 1
                print(f"  [FINDING] {c.name}: engine recorded {_fmt(c.live, 4)}, "
                      f"recomputed from the recorded bars {_fmt(c.recomputed, 4)}")

        # --- 2. shadow parity
        #
        # A sleeve the engine actually traded and the shadow did not reproduce
        # is a FINDING, not a footnote. On 2026-08-10 both sleeves landed here
        # and the report still signed off "shadow and live agree" — the failure
        # this section exists to make impossible.
        traded = bool(row is not None and row["gate_ok"] and row["filter_ok"])
        cov = bar_coverage(bars)
        if traded and not sh.ran:
            findings += 1
            unverified.append((sym, sh.reason))
            print(f"\n  [FINDING] shadow: did not run — {sh.reason}")
            print("            this sleeve traded, so NOTHING was compared for it")
        else:
            print(f"\n  shadow: {'ran' if sh.ran else 'did not run — ' + sh.reason}")
        if traded and sh.ran:
            if cov.complete:
                compared.append(sym)
            else:
                truncated.append((sym, cov))
                print(f"  [WARN] bars recorded end at idx {cov.last_idx}, "
                      f"{cov.missing} short of the last holding bar "
                      f"({LAST_HOLDING_IDX}) — the shadow is force-flattened "
                      f"early and understates itself")
        if sh.ran or live:
            print(f"    {'':<4} {'LIVE':<38}{'SHADOW (backtest fills)':<38}")
            print(f"    {'#':<4} {'bars':<9} {'entry':>8} {'exit':>8}  {'out':<9}"
                  f"{'bars':<9} {'entry':>8} {'exit':>8}  {'out':<9}")
            for i in range(max(len(live), len(sh.trades))):
                lt = live[i] if i < len(live) else None
                st = sh.trades[i] if i < len(sh.trades) else None
                blank = f"{'—':<9} {'—':>8} {'—':>8}  {'—':<9}"
                lc = (f"{str(lt.entry_bar) + '>' + str(lt.exit_bar):<9} "
                      f"{_fmt(lt.entry_px):>8} {_fmt(lt.exit_px):>8}  "
                      f"{lt.outcome:<9}") if lt else blank
                sc = (f"{str(st.entry_bar) + '>' + str(st.exit_bar):<9} "
                      f"{_fmt(st.entry_px):>8} {_fmt(st.exit_px):>8}  "
                      f"{st.outcome:<9}") if st else blank
                print(f"    {i+1:<4} {lc}{sc}")

            # **Both sides must be the same quantity, and for a while they were
            # not.** The shadow is `sm.pnl` — `qty x (exit - entry) / capital`,
            # accumulated by `sleeve.py:on_exit_fill`. The live side summed
            # `exit / entry - 1` instead, on a comment asserting those were the
            # same thing. They coincide only when `qty x entry == capital`,
            # which §2.4 breaks by design: quantity is sized off `limit_px` and
            # the fill may gap through it.
            #
            # On 2026-08-13 the re-entry gapped 4.0% through its limit, so the
            # two definitions differed by 7.1 bp and the report announced a
            # 0.75 bp gap where the like-for-like figure was 7.85 bp — while
            # the engine's own EOD line said `pnl=-555.6bp`, agreeing with the
            # shadow's definition and not with the report's. A parity report
            # whose headline disagrees with the engine it is auditing is worse
            # than no report. The error scales with gap-through depth, so it is
            # largest exactly on the days worth reading closely.
            cap = _num(row, "sleeve_capital") if row is not None else None
            lbp, comparable = day_bp(live, cap)
            sbp = 1e4 * sh.pnl
            print(f"\n    trades   live {len(live):<3}  shadow {len(sh.trades)}")
            if comparable:
                print(f"    bp/day   live {_fmt(lbp):<7}  shadow {_fmt(sbp):<7}  "
                      f"gap {_fmt(lbp - sbp)}   "
                      f"(qty x (exit-entry) / sleeve capital, both sides)")
            else:
                findings += 1
                print(f"    bp/day   live {_fmt(lbp):<7}  shadow {_fmt(sbp):<7}")
                print("    [FINDING] no sleeve_capital recorded, so the live "
                      "figure is summed price returns and the shadow is not — "
                      "these two numbers are NOT comparable and no gap is shown")
            if len(live) != len(sh.trades) and sh.ran:
                findings += 1
                print("    [FINDING] trade-count mismatch: the fill models "
                      "disagree on how many round trips this session held")

        # --- multi-execution entries (defect 8's signature)
        multi = [t for t in live if t.n_entry_execs > 1]
        if multi:
            print(f"\n  entries settled in multiple executions: {len(multi)} "
                  f"({', '.join(str(t.n_entry_execs) for t in multi)}) — "
                  f"the bracket must have covered the whole position each time")

        # --- 3. S10/S11
        q1 = [f for f in fills_without_quotes(store, sym, session) if f.suspicious]
        if q1:
            findings += len(q1)
            print(f"\n  [FINDING] {len(q1)} entry fill(s) with no recorded quote "
                  f"reaching the limit:")
            for f in q1:
                print(f"      bar {f.bar}: filled {_fmt(f.price)} on a limit of "
                      f"{_fmt(f.limit_px)}, best bid seen {_fmt(f.best_bid_seen)} "
                      f"over {f.n_quotes} quotes")

        reentries = same_bar_reentries(live, sh.trades)
        if reentries:
            print("\n  same-bar re-entries (S10 — the sharpest available test):")
            for r in reentries:
                adv = r.shadow_advantage_bp
                print(f"      bar {r.bar}: prev exit {_fmt(r.prev_exit_px)}  "
                      f"live {_fmt(r.live_entry_px)}"
                      f"{' (below the exit)' if r.live_better else ''}  "
                      f"shadow {_fmt(r.shadow_entry_px)}"
                      f"{' (below the exit)' if r.shadow_better else ''}"
                      + (f"  shadow advantage {_fmt(adv)} bp" if adv else ""))

            both = [r for r in reentries if r.shadow_advantage_bp is not None]
            if both:
                mean_adv = sum(r.shadow_advantage_bp for r in both) / len(both)
                print(f"      mean shadow advantage over {len(both)} shared "
                      f"event(s): {_fmt(mean_adv)} bp")
            # §5 question 2, answered directly.
            answered = [r for r in reentries if r.live_better is not None]
            if answered:
                worse = sum(1 for r in answered if not r.live_better)
                print(f"      §5 Q2 — live re-entry at or worse than the price "
                      f"just sold: {worse} of {len(answered)}")
            ghosts = [r for r in reentries if r.live_entry_px is None]
            if ghosts:
                print(f"      {len(ghosts)} re-entry(ies) the backtest books that "
                      f"the live session never had — the S10 population")

        # --- 4. slippage
        slips = slippage(store, sym, session)
        graded = [s for s in slips if s.vs_limit is not None]
        if graded:
            avg = sum(s.vs_limit for s in graded) / len(graded)
            worse = sum(1 for s in graded if s.vs_limit > 0)
            print(f"\n  slippage vs the resting limit: {len(graded)} entry "
                  f"execution(s), mean {_fmt(avg)} bp, {worse} adverse "
                  f"(positive == worse than the limit)")
        gaps = [s for s in slips if s.gap_through]
        if gaps:
            worst = min(s._raw_vs_limit() for s in gaps)
            print(f"\n  gap-through entries: {len(gaps)} execution(s) filled far "
                  f"below the resting limit (worst {_fmt(worst)} bp)")
            print(f"      Not slippage. §2.5 prices the entry 1% under a rolling "
                  f"session high, so once price falls away from that high the "
                  f"limit is marketable and the fill is unrelated to it.")
            print(f"      The backtest models this — it fills a gap-through at "
                  f"the bar open — so the shadow above is the check that matters, "
                  f"not this number.")
        mids = [s for s in slips if s.role == "E" and s.vs_mid is not None]
        if mids:
            m = sum(s.vs_mid for s in mids) / len(mids)
            print(f"\n  entry fills vs the quote while the order worked: "
                  f"{len(mids)} execution(s), mean {_fmt(m)} bp "
                  f"(the honest execution number)")

        # --- 5. the exit side
        #
        # Everything above this line grades entries. A session can lose its
        # whole result in the exit — 2026-08-12 lost 59 bp of 152 in the 15:55
        # flatten — and the report used to have no line about it, which made the
        # instrument unable to answer the first question asked of it that day.
        exits = exit_quality(slips)
        if exits:
            print("\n  exit fills vs the quote standing when they printed:")
            for e in exits:
                print(f"      {EXIT_OUTCOME.get(e.role, e.role):<9} "
                      f"{e.n_execs:>3} execution(s)  {e.qty:>7,.0f} sh  "
                      f"@ {_fmt(e.px):>9}  {_fmt(e.vs_mid_bp):>8} bp"
                      f"  (positive == worse)")

        fc = flatten_cost(slips, bars)
        if fc is not None:
            print(f"\n  the 15:55 flatten — a MARKET order (§4.7: MKT, not MOC, "
                  f"because §1 puts being flat above the fill price):")
            print(f"      {fc.qty:,.0f} share(s) in {fc.n_execs} execution(s), "
                  f"vwap {_fmt(fc.live_px)}")
            if fc.ref_px is None:
                print(f"      bar {LAST_HOLDING_IDX} was not recorded, so there "
                      f"is nothing to price the flatten against — "
                      f"`record_session_tail` is what backfills it")
            else:
                print(f"      the backtest exits this trade at the bar "
                      f"{LAST_HOLDING_IDX} close ({_fmt(fc.ref_px)}), free and "
                      f"on time; live paid {_fmt(fc.bp)} bp = "
                      f"{_fmt(fc.dollars)} against that")
            if fc.vs_mid_bp is None:
                print("      no quote was recorded beside the flatten fills, so "
                      "the spread and the market's move cannot be separated")
            else:
                print(f"      of which spread-crossing is {_fmt(fc.vs_mid_bp)} "
                      f"bp — the fill against the quote at the moment it "
                      f"printed. The rest is the market moving between 15:55 "
                      f"and the fill, which no order type would have avoided.")
                if fc.vs_mid_bp > FLATTEN_VS_QUOTE_BP:
                    findings += 1
                    print(f"      [FINDING] {_fmt(fc.vs_mid_bp)} bp against the "
                          f"standing quote is not a spread on a liquid ETF — "
                          f"this is the execution itself, not the market.")

    # ------------------------------------------------------------- sign-off
    #
    # This line is the one a human reads when they read nothing else, so it may
    # only claim what was actually established. The 2026-08-10 report printed
    # "Shadow and live agree" having compared nothing at all on either sleeve.
    # Every clause below is now conditioned on a comparison having happened.
    print(f"\n{_rule()}")
    if findings:
        print(f"{findings} finding(s) needing a human.")
    if unverified:
        print("NOT VERIFIED — the shadow did not run on: "
              + ", ".join(f"{s} ({why})" for s, why in unverified))
        print("  No agreement is claimed for those sleeves. Nothing was compared.")
    if truncated:
        print("PARTIALLY VERIFIED — bar record ends before the last holding bar on: "
              + ", ".join(f"{s} (short {c.missing})" for s, c in truncated))
        print("  Those shadows force-flatten early, so the live-vs-shadow gap on "
              "them is overstated in live's favour.")
    if compared and not findings and not truncated:
        print(f"No findings. Shadow and live agree on "
              f"{', '.join(compared)}, over the complete tradable session.")
    elif not findings and not unverified and not truncated:
        # Nothing traded — a real and ordinary outcome, and not an agreement.
        print("No findings. No sleeve traded, so there was nothing to compare.")
    print(_rule())
    return findings


