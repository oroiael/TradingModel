#: §8's rule: "Investigate structural breaks, not noise: a month where fill
#: counts or ON-rates deviate >20% from expectation means the market or the
#: execution has changed, not luck."
STRUCTURAL_BREAK = 0.20

#: §8 says *a month*, and the rule is worthless without that qualifier: on a
#: three-session sample every metric deviates by more than 20% and the report
#: would open every week by crying wolf. Defects 6 and 7 (`PROJECT_STATUS.md`
#: §4.7) were both checks that fired on healthy days and each cost a session —
#: "a safety check that fires on healthy days is not a safety feature".
MIN_SESSIONS_FOR_BREAK = 20

#: The roles `orders.py` writes. "E" is the only buy side; the other three are
#: exits and double as the outcome label.
EXIT_OUTCOME = {"T": "target", "S": "stop", "F": "flatten"}

#: `orders.py:ROLE_FLAT`, transcribed rather than imported for the same reason
#: `EXIT_OUTCOME` is: `orders.py` reaches the broker and this module must not.
ROLE_FLATTEN = "F"

#: A SELL crossing the spread on a penny-wide $145 ETF costs well under a basis
#: point, so a flatten filling this far under the quote *that was standing when
#: it printed* is not the spread — it is a routing or a sizing problem worth a
#: human. Deliberately loose: §4.7's flatten is a market order and is expected
#: to pay something every session, and "a safety check that fires on healthy
#: days is not a safety feature" (defects 6 and 7). This one cannot fire on the
#: market having moved after 15:55, because the quote it compares against is
#: the one at the fill.
FLATTEN_VS_QUOTE_BP = 50.0

#: Quantity tolerance when deciding a round trip has closed. Shares are whole
#: live, but the comparison is written in floats and a fractional residue from
#: a bad row should not silently open a phantom trade.
QTY_EPS = 1e-6


# ------------------------------------------------------------------- helpers
def _fmt(x: Optional[float], nd: int = 2, dash: str = "—") -> str:
    if x is None:
        return dash
    if isinstance(x, float) and x != x:          # NaN
        return dash
    return f"{x:,.{nd}f}"


def _pct(x: Optional[float], nd: int = 1) -> str:
    return "—" if x is None else f"{x * 100:,.{nd}f}%"


def _num(row, key: str) -> Optional[float]:
    """A float from a `daily` row, or None if it is absent or unparseable.

    The daily row is written in three passes (§`store.daily`), so a session
    interrupted between them leaves real NULLs. This file must report that, not
    raise a TypeError in the middle of a post-session review.
    """
    try:
        v = row[key]
    except (KeyError, IndexError):
        return None
    if v is None:
        return None
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return None if f != f else f          # NaN is not a usable input either


def bar_idx_of(ts: str) -> Optional[int]:
    """Bar index for a UTC ISO timestamp, on the §2.1 clock (0 is 09:30 ET).

    Returns None outside the session. This is the same offset arithmetic
    `spec_constants.bar_index` does for a wall-clock string, but starting from
    a stored timestamp — and it is deliberately zone-aware, because the defect
    that cost a whole session (`PROJECT_STATUS.md` §4.6) was a naive local
    time producing `Bar.idx = -36`.
    """
    try:
        dt = datetime.fromisoformat(ts)
    except (TypeError, ValueError):
        return None
    if dt.tzinfo is None:
        return None
    et = dt.astimezone(ET)
    oh, om = (int(v) for v in SESSION_OPEN.split(":"))
    delta = (et.hour * 60 + et.minute) - (oh * 60 + om)
    if delta < 0:
        return None
    return delta // BAR_MINUTES


def session_label(session: str) -> str:
    """`20260806` -> `2026-08-06`; anything else is returned unchanged."""
    if len(session) == 8 and session.isdigit():
        return f"{session[:4]}-{session[4:6]}-{session[6:]}"
    return session


# --------------------------------------------------------------- store reads
def sessions_in(store: Store) -> list[str]:
    return [r["session"] for r in
            store.rows("SELECT DISTINCT session FROM daily ORDER BY session")]


def symbols_in(store: Store, session: str) -> list[str]:
    return [r["symbol"] for r in store.rows(
        "SELECT DISTINCT symbol FROM daily WHERE session=? ORDER BY symbol",
        (session,))]


def daily_row(store: Store, symbol: str, session: str):
    rows = store.rows("SELECT * FROM daily WHERE session=? AND symbol=?",
                      (session, symbol))
    return rows[0] if rows else None


def recorded_bars(store: Store, symbol: str, session: str) -> list[Bar]:
    """The bars the engine actually decided on, from the `bars` table."""
    return [Bar(int(r["bar_idx"]), float(r["open"]), float(r["high"]),
                float(r["low"]), float(r["close"]), float(r["volume"] or 0.0))
            for r in store.session_bars(symbol, session)]


def entry_limits(store: Store, symbol: str, session: str) -> dict[int, float]:
    """bar_idx -> the resting BUY LIMIT price, from the order log.

    Used by the slippage and S10 sections to know what price the engine was
    actually working when a fill arrived.
    """
    out: dict[int, float] = {}
    for r in store.rows(
            "SELECT * FROM orders WHERE session=? AND symbol=? AND role='E' "
            "AND event IN ('placed','modified') ORDER BY ts", (session, symbol)):
        idx = bar_idx_of(r["ts"])
        if idx is not None and r["limit_px"] is not None:
            out[idx] = float(r["limit_px"])
    return out


# ------------------------------------------------- live trade reconstruction
@dataclass
class LiveTrade:
    """One round trip, rebuilt from executions rather than from orders.

    **Executions, not orders, is the load-bearing choice here.** Defect 8
    (`PROJECT_STATUS.md` §4.7) was exactly the mistake of reading one order as
    one fill: IBKR settled 541 shares as 300 + 210 + 31. A report that
    reconstructed trades order-by-order would reproduce the defect it exists to
    detect. Walking executions and closing the trade when the position returns
    to flat is robust to any split.
    """
    entry_bar: Optional[int]
    exit_bar: Optional[int]
    entry_px: float               # quantity-weighted over all entry executions
    exit_px: float                # quantity-weighted over all exit executions
    qty: float
    outcome: str                  # "target" | "stop" | "flatten" | "open"
    n_entry_execs: int = 0
    n_exit_execs: int = 0
    limit_px: Optional[float] = None

    @property
    def ret(self) -> float:
        """The *price* return of the round trip. Not the sleeve's return.

        These differ whenever the entry filled away from the limit it was sized
        off, which §2.4 makes routine: quantity comes from `limit_px` and the
        fill can gap through it. On 2026-08-13 the re-entry was sized off 152.59
        and filled at 146.63 — a 4.0% gap-through — so the position was 4.0%
        smaller than sleeve capital and the sleeve's return was 4.0% smaller
        than this number. Use `ret_on_capital` for anything compared against
        the shadow, the engine's own P&L, or §8.
        """
        return (self.exit_px / self.entry_px - 1.0) if self.entry_px else 0.0

    @property
    def pnl(self) -> float:
        return (self.exit_px - self.entry_px) * self.qty

    def ret_on_capital(self, capital: Optional[float]) -> Optional[float]:
        """`qty x (exit - entry) / sleeve_capital` — what `sleeve.py` books.

        The one definition that is comparable to anything else in the project:
        `SleeveStateMachine.on_exit_fill` accumulates exactly this into
        `sm.pnl`, the engine logs it as the day's `pnl=`, and §8's published
        figures are the backtest's version of it.
        """
        if not capital:
            return None
        return self.pnl / capital


def day_bp(trades: Sequence[LiveTrade],
           capital: Optional[float]) -> tuple[float, bool]:
    """(basis points, comparable). Closed round trips only.

    `comparable` is False when no sleeve capital was recorded and the figure
    falls back to summed price returns — which is *not* the same quantity as
    the shadow's. Returning that silently is how the two sides came to be
    computed differently in the first place, so the caller has to be told.
    """
    closed = [t for t in trades if t.outcome != "open"]
    if capital:
        return 1e4 * sum(t.pnl for t in closed) / capital, True
    return 1e4 * sum(t.ret for t in closed), False


def live_trades(store: Store, symbol: str, session: str) -> list[LiveTrade]:
    """Round trips from the `fills` table, in execution order."""
    limits = entry_limits(store, symbol, session)
    out: list[LiveTrade] = []

    pos = 0.0
    e_notional = e_qty = x_notional = x_qty = 0.0
    e_execs = x_execs = 0
    entry_bar: Optional[int] = None
    exit_bar: Optional[int] = None
    outcome = "open"
    limit_px: Optional[float] = None

    for f in store.session_fills(symbol, session):
        qty = float(f["qty"] or 0.0)
        px = float(f["price"] or 0.0)
        if qty <= 0.0:
            continue
        idx = bar_idx_of(f["ts"])
        buy = (f["side"] == "BOT") or (f["role"] == "E")

        if buy:
            if pos <= QTY_EPS:
                entry_bar = idx
                # The limit that was resting when this entry began. Fall back to
                # the most recent one at or before the fill bar.
                cands = [b for b in limits if idx is None or b <= idx]
                limit_px = limits[max(cands)] if cands else None
            e_notional += qty * px
            e_qty += qty
            e_execs += 1
            pos += qty
        else:
            x_notional += qty * px
            x_qty += qty
            x_execs += 1
            exit_bar = idx
            outcome = EXIT_OUTCOME.get(f["role"] or "", "flatten")
            pos -= qty
            if pos <= QTY_EPS and e_qty > 0.0:
                out.append(LiveTrade(
                    entry_bar=entry_bar, exit_bar=exit_bar,
                    entry_px=e_notional / e_qty, exit_px=x_notional / x_qty,
                    qty=x_qty, outcome=outcome,
                    n_entry_execs=e_execs, n_exit_execs=x_execs,
                    limit_px=limit_px))
                pos = 0.0
                e_notional = e_qty = x_notional = x_qty = 0.0
                e_execs = x_execs = 0
                entry_bar = exit_bar = None
                limit_px = None

    # Still long at the end of the record: the flatten did not complete, or the
    # report is being run mid-session. Either way it must be visible.
    if e_qty > 0.0 and pos > QTY_EPS:
        out.append(LiveTrade(entry_bar=entry_bar, exit_bar=None,
                             entry_px=e_notional / e_qty, exit_px=float("nan"),
                             qty=pos, outcome="open", n_entry_execs=e_execs,
                             n_exit_execs=x_execs, limit_px=limit_px))
    return out


# --------------------------------------------------------------- the shadow
@dataclass
class Shadow:
    """What the backtest books on the same bars, with the same config."""
    trades: list[Trade]
    pnl: float
    fills: int
    stop_outs: int
    ran: bool
    reason: str = ""


def shadow_replay(bars: Sequence[Bar], row) -> Shadow:
    """Drive the recorded bars through the live state machine.

    The gate and filter are **not re-decided**. They are replayed from what the
    engine recorded in `daily`, so this diff isolates the order path. Feature
    arithmetic is checked separately (`feature_parity`), which is the right
    place for it: a feature bug and a fill bug want different fixes and mixing
    them into one number hides both.

    The config is the *live* config — tick rounding on, whole shares, §2.4
    limit-price sizing — for the same reason. The only thing that differs from
    the real session is who decided the fills.
    """
    if row is None:
        return Shadow([], 0.0, 0, 0, False, "no daily row")
    if not row["gate_ok"]:
        return Shadow([], 0.0, 0, 0, False, row["gate_reason"] or "gate_off")
    if not row["filter_ok"]:
        return Shadow([], 0.0, 0, 0, False, row["filter_reason"] or "stood_down")
    if not bars:
        return Shadow([], 0.0, 0, 0, False, "no bars recorded")

    capital = _num(row, "sleeve_capital")
    if capital is None:
        return Shadow([], 0.0, 0, 0, False, "no sleeve_capital recorded")
    missing = [k for k in ("atr5", "or30", "thr80", "pos10")
               if _num(row, k) is None]
    if missing:
        return Shadow([], 0.0, 0, 0, False,
                      f"daily row is missing {', '.join(missing)}")

    cfg = SleeveConfig(symbol=row["symbol"], sleeve_capital=capital)
    sm = SleeveStateMachine(cfg)

    # §2.2's gate is **not re-decided here**, and re-deriving its inputs from
    # the recorded bars is what made this whole section dead on arrival.
    #
    # `SessionStats.is_half_day` is `last bar idx < FLATTEN_IDX`, and
    # FLATTEN_IDX is the 15:55 bar the engine flattens *at* — so a live session
    # never records it, every real day recomputed as a half day, and the shadow
    # refused on 2026-08-10 for both sleeves while the report still printed
    # "shadow and live agree".
    #
    # The recorded gate decision is the evidence. `gate_decision` returns
    # `gate_on` only when both flags were False, so `gate_ok=1` in the daily row
    # *is* the statement that this was a full session which opened on time.
    # Replaying those values reproduces the engine's decision instead of
    # second-guessing it from data the engine never had.
    gate = sm.begin_session(row["session"], _num(row, "atr5"),
                            is_half_day=False, late_open=False)
    if not gate.ok:
        # Only ATR5 can refuse now, so this is a genuine disagreement: the
        # recorded ATR5 does not clear the gate the engine passed on it.
        return Shadow([], 0.0, 0, 0, False,
                      f"shadow gate refused on recorded atr5="
                      f"{_num(row, 'atr5'):.2f}: {gate.reason}")
    filt = sm.apply_morning_filter(_num(row, "or30"), _num(row, "thr80"),
                                   _num(row, "pos10"))
    if not filt.ok:
        return Shadow([], 0.0, 0, 0, False, f"shadow filter refused: {filt.reason}")

    replay_session(list(bars), sm, fill_model="spec")
    return Shadow(sm.trades, sm.pnl, sm.fills, sm.stop_outs, True)


@dataclass
class Coverage:
    """How much of the tradable session the recorded bars actually span.

    The engine flattens *at* FLATTEN_IDX and stops, so on 2026-08-10 it
    recorded 76 bars — idx 0..75 — while `LAST_HOLDING_IDX` is 76. The shadow
    is therefore force-flattened at bar 75 by `replay_session`'s tail rule,
    while the live session went on trading in bar 76. On that session it cost
    the comparison **68 bp on SOXS alone** (233.04 against 301.44 with the full
    session), all of it in the one trade that exited after the record ended.

    A comparison drawn against a truncated record is not wrong so much as
    *unearned*, and the report has to say which it is.
    """
    n_bars: int
    last_idx: Optional[int]
    missing: int

    @property
    def complete(self) -> bool:
        return self.last_idx is not None and self.last_idx >= LAST_HOLDING_IDX


def bar_coverage(bars: Sequence[Bar]) -> Coverage:
    if not bars:
        return Coverage(0, None, LAST_HOLDING_IDX + 1)
    last = max(b.idx for b in bars)
    return Coverage(len(bars), last, max(0, LAST_HOLDING_IDX - last))


# ------------------------------------------------------------ feature parity
@dataclass
class FeatureCheck:
    name: str
    live: Optional[float]
    recomputed: Optional[float]
    tol: float

    @property
    def ok(self) -> bool:
        if self.live is None or self.recomputed is None:
            return False
        return abs(self.live - self.recomputed) <= self.tol


def feature_parity(bars: Sequence[Bar], row) -> list[FeatureCheck]:
    """Recompute §2.1's session quantities from the recorded bars.

    This is the check that would have caught the `America/Los_Angeles` defect
    without costing a session: if the bars were indexed wrongly, the opening
    range recomputed from them will not match the OR30 the engine recorded.
    """
    if not bars or row is None:
        return []
    stats = session_stats(bars)
    def _get(k):
        v = row[k]
        return None if v is None else float(v)
    return [
        FeatureCheck("or30", _get("or30"), stats.or30, 1e-6),
        FeatureCheck("pos10", _get("pos10"), stats.pos10, 1e-6),
    ]


# ------------------------------------------------------------------ slippage
@dataclass
class SlipRow:
    bar: Optional[int]
    role: str
    side: str
    qty: float
    price: float
    limit_px: Optional[float]
    mid: Optional[float]

    #: A buy filling further below its limit than this is not price improvement
    #: — it is evidence the limit was never near the market. §2.5 prices the
    #: entry 1% below a *rolling session high*, so once price has fallen away
    #: from that high the limit is marketable and the fill has nothing to do
    #: with it. SOXL on 2026-08-10: limit 142.02 off a 09:30 high of 143.45,
    #: filled at 135.69, and the report called −445.71 bp "0 adverse".
    GAP_THROUGH_BP = 100.0

    @property
    def gap_through(self) -> bool:
        """Did this fill happen far away from the limit that was resting?"""
        raw = self._raw_vs_limit()
        return raw is not None and raw < -self.GAP_THROUGH_BP

    def _raw_vs_limit(self) -> Optional[float]:
        if self.limit_px in (None, 0):
            return None
        raw = (self.price / self.limit_px - 1.0) * 1e4
        return raw if self.side == "BOT" else -raw

    @property
    def vs_limit(self) -> Optional[float]:
        """Signed, in basis points, positive == worse than the limit.

        A BUY filling above its limit and a SELL filling below it are both
        adverse, so the sign is flipped on the sell side.

        **None for a gap-through.** Comparing the fill to a limit the market
        had already run past measures the distance travelled since the session
        high, not execution quality, and averaging it in buries the fills that
        say something. Those are reported separately, and `vs_mid` — the quote
        while the order was actually working — is the honest execution number.
        """
        raw = self._raw_vs_limit()
        return None if raw is None or self.gap_through else raw

    @property
    def vs_mid(self) -> Optional[float]:
        if self.mid in (None, 0):
            return None
        raw = (self.price / self.mid - 1.0) * 1e4
        return raw if self.side == "BOT" else -raw


def slippage(store: Store, symbol: str, session: str) -> list[SlipRow]:
    limits = entry_limits(store, symbol, session)
    out = []
    for f in store.session_fills(symbol, session):
        idx = bar_idx_of(f["ts"])
        role = f["role"] or "?"
        bid, ask = f["bid"], f["ask"]
        mid = (float(bid) + float(ask)) / 2.0 if bid and ask else None
        lim = None
        if role == "E":
            cands = [b for b in limits if idx is None or b <= idx]
            lim = limits[max(cands)] if cands else None
        out.append(SlipRow(bar=idx, role=role, side=f["side"] or "",
                           qty=float(f["qty"] or 0.0), price=float(f["price"] or 0.0),
                           limit_px=lim, mid=mid))
    return out


# --------------------------------------------------------- the 15:55 flatten
@dataclass
class ExitQuality:
    """Exit executions against the quote that was standing when they printed.

    **The exit side had no measurement at all.** `vs_limit` is None for every
    role but "E" — an exit has no resting entry limit to be graded against — and
    the "honest execution number" filtered to `role == "E"` as well. So a
    session whose whole result turned in its last bar produced a report with no
    line in it about that bar, and the first question anyone asks after such a
    session ("what did the exit cost us?") could not be answered from the
    instrument built to answer exactly that kind of question.

    Every fill already carries a quote: `orders.py:_record_fill` stamps bid/ask
    onto *every* execution regardless of role. Nothing new has to be recorded —
    this only reads what was already there.
    """
    role: str
    n_execs: int
    qty: float
    px: float                       # quantity-weighted over the executions
    vs_mid_bp: Optional[float]      # quantity-weighted; positive == worse


@dataclass
class FlattenCost:
    """What the 15:55 market order cost against the price the backtest books.

    `orders.py:_flatten` sends a **MKT** — §4.7, deliberately not a MOC, because
    §1's first design priority is never holding overnight and a MOC can be
    neither modified nor re-sent when it comes back short. The live exit
    therefore takes whatever the tape gives it from 15:55 onward, while
    `replay_session`'s tail rule books the backtest's flatten at the **close of
    `LAST_HOLDING_IDX`** — the 15:55:00 print, no spread, no delay, no
    uncertainty about when the order actually went out.

    That gap is a real and recurring cost of running the strategy which the
    backtest does not carry, and it belongs in the report next to the shadow it
    explains. On 2026-08-12 SOXL's shadow flattened at 142.99 and the live
    session at 142.15 — 59 bp, most of the day's loss — and the report said
    nothing about it at all.

    **`bp` and `vs_mid_bp` are different quantities and the distinction is the
    whole point.** `bp` is the total: spread plus however far the market
    travelled between 15:55:00 and the fill. `vs_mid_bp` is the spread-crossing
    alone, because it prices the fill against the quote standing when it
    printed. A large `bp` with a small `vs_mid_bp` means the market moved and
    the order was filled fairly; a large `vs_mid_bp` means the execution itself
    was bad. Only the second is a defect.
    """
    qty: float
    live_px: float                  # quantity-weighted over the flatten fills
    ref_px: Optional[float]         # close of LAST_HOLDING_IDX
    n_execs: int
    vs_mid_bp: Optional[float]

    @property
    def bp(self) -> Optional[float]:
        """Signed, positive == the market order beat the backtest's price."""
        if not self.ref_px or not self.live_px:
            return None
        return (self.live_px / self.ref_px - 1.0) * 1e4

    @property
    def dollars(self) -> Optional[float]:
        """Signed dollars on the shares actually flattened.

        The one number here that is not a ratio, and the one a human asks for
        first. It is exact: both prices and the quantity are recorded.
        """
        if self.ref_px is None:
            return None
        return (self.live_px - self.ref_px) * self.qty


def _wavg_vs_mid(rows: Sequence[SlipRow]) -> Optional[float]:
    """Quantity-weighted `vs_mid`, or None when no fill carried a quote.

    Quantity-weighted rather than a plain mean because IBKR splits one order
    across executions of wildly different sizes — a 27-share tail must not
    count the same as the 497 shares it followed.
    """
    num = den = 0.0
    for s in rows:
        if s.vs_mid is None or s.qty <= 0.0:
            continue
        num += s.qty * s.vs_mid
        den += s.qty
    return (num / den) if den else None


def exit_quality(slips: Sequence[SlipRow]) -> list[ExitQuality]:
    """Per-role exit execution, in the order the roles matter."""
    out = []
    for role in ("T", "S", ROLE_FLATTEN, "X"):
        rows = [s for s in slips if s.role == role and s.qty > 0.0]
        if not rows:
            continue
        qty = sum(s.qty for s in rows)
        out.append(ExitQuality(
            role=role, n_execs=len(rows), qty=qty,
            px=sum(s.qty * s.price for s in rows) / qty,
            vs_mid_bp=_wavg_vs_mid(rows)))
    return out


def flatten_cost(slips: Sequence[SlipRow],
                 bars: Sequence[Bar]) -> Optional[FlattenCost]:
    """The 15:55 flatten priced against the bar the backtest exits on.

    None when the session never flattened. A day that ended on a target or a
    stop paid this cost nothing, and printing a zero for it would put a line in
    every report that means nothing on most of them.
    """
    rows = [s for s in slips if s.role == ROLE_FLATTEN and s.qty > 0.0]
    if not rows:
        return None
    qty = sum(s.qty for s in rows)
    ref = next((b.close for b in bars if b.idx == LAST_HOLDING_IDX), None)
    return FlattenCost(qty=qty,
                       live_px=sum(s.qty * s.price for s in rows) / qty,
                       ref_px=ref, n_execs=len(rows),
                       vs_mid_bp=_wavg_vs_mid(rows))


