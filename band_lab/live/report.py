"""
Stage 6 — the measurement instrument.

`PROJECT_STATUS.md` §3: "without it the paper run produces fills nobody diffs
against the backtest, which is the *entire reason to launch*." This is that
diff.

Four questions, in the order they matter:

  1. **Shadow parity.** Replay the session's own recorded bars through the same
     state machine that traded them, with the backtest's bar-granularity fill
     rules, and diff the simulated trades against the real ones. A live
     shortfall is then attributable to *fills* rather than to a coding error —
     `replay.py` already established the state machine and the backtest agree
     (779 = 779 ON-days, max daily P&L difference 0.0), so anything this report
     finds is execution.

  2. **S10/S11.** `PHASE2_PARITY.md` S10 predicts a systematic gap on same-bar
     re-entries specifically, and says paper trading tests it "in the fill
     prices themselves, within days, on the very first ON-days". §5 asks the
     two questions directly and this answers them from `fills` and `quotes`.

  3. **Slippage.** Realised, per fill, against the limit that was resting and
     against the mid at decision time.

  4. **§8 monitoring.** The published baselines computed on live data, with the
     >20% structural-break rule the spec asks for. Baselines are read from
     `phase1/out/monitoring_expectations.csv` rather than re-transcribed — that
     file is regenerated by `parity.py` and re-typing the numbers here would
     create a second source of truth.

**This module is read-only and has no broker.** It imports no `ib_async`, opens
the store without writing to it, and can be run at any time against a database
being written by a live session — SQLite WAL permits the concurrent reader.
Nothing it computes feeds back into a trading decision, by construction:
`store.py`'s header makes the broker the only source of state, and a reporting
tool that could steer the engine would break that.

Run:
    python3 band_lab/live/report.py                     # latest session in the db
    python3 band_lab/live/report.py --session 20260806
    python3 band_lab/live/report.py --weekly            # §8, all sessions
    python3 band_lab/live/report.py --all --csv out/
"""

